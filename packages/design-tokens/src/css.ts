import { colors, elevation, motion, radii, typography, type SemanticColors } from "./tokens.ts";

export const kebab = (s: string): string => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

const colorVars = (c: SemanticColors, indent: string): string =>
  Object.entries(c)
    .map(([k, v]) => `${indent}--hx-color-${kebab(k)}: ${v};`)
    .join("\n");

const shadowVars = (scheme: "light" | "dark", indent: string): string =>
  Object.entries(elevation[scheme])
    .map(([k, v]) => `${indent}--hx-shadow-${k}: ${v};`)
    .join("\n");

/** Names of every semantic colour variable, e.g. `--hx-color-text-muted`. */
export const colorVariableNames = (Object.keys(colors.light) as (keyof SemanticColors)[]).map(
  (k) => `--hx-color-${kebab(k)}`,
);

/**
 * CSS custom properties for both schemes. Light is the default; dark applies with
 * `data-theme="dark"` on <html>, or automatically via prefers-color-scheme unless the user pinned
 * `data-theme="light"`.
 */
export function buildTokensCss(): string {
  const statics = [
    ...Object.entries(radii).map(([k, v]) => `  --hx-radius-${k}: ${v};`),
    ...Object.entries(typography.family).map(([k, v]) => `  --hx-font-family-${k}: ${v};`),
    ...Object.entries(motion.duration).map(([k, v]) => `  --hx-duration-${k}: ${v};`),
    ...Object.entries(motion.easing).map(([k, v]) => `  --hx-ease-${k}: ${v};`),
  ].join("\n");

  return `/* GENERATED by @healuxa/design-tokens (scripts/build-css.ts). Do not edit. */
:root {
  color-scheme: light;
${statics}
${colorVars(colors.light, "  ")}
${shadowVars("light", "  ")}
}

:root[data-theme="dark"] {
  color-scheme: dark;
${colorVars(colors.dark, "  ")}
${shadowVars("dark", "  ")}
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${colorVars(colors.dark, "    ")}
${shadowVars("dark", "    ")}
  }
}

@media (prefers-reduced-motion: reduce) {
  :root {
${Object.keys(motion.duration)
  .map((k) => `    --hx-duration-${k}: 0ms;`)
  .join("\n")}
  }
}
`;
}

/** Tailwind CSS v4 theme mapping utilities (bg-surface, text-muted, rounded-lg…) onto the variables. */
export function buildTailwindThemeCss(): string {
  const colorLines = (Object.keys(colors.light) as (keyof SemanticColors)[])
    .map((k) => `  --color-${kebab(k)}: var(--hx-color-${kebab(k)});`)
    .join("\n");
  const fontLines = Object.keys(typography.family)
    .map((k) => `  --font-${k}: var(--hx-font-family-${k});`)
    .join("\n");
  const textLines = Object.entries(typography.scale)
    .map(([k, [size, lh]]) => `  --text-${k}: ${size};\n  --text-${k}--line-height: ${lh};`)
    .join("\n");
  const radiusLines = Object.keys(radii)
    .filter((k) => k !== "none" && k !== "full")
    .map((k) => `  --radius-${k}: var(--hx-radius-${k});`)
    .join("\n");
  const shadowLines = Object.keys(elevation.light)
    .filter((k) => k !== "none")
    .map((k) => `  --shadow-${k}: var(--hx-shadow-${k});`)
    .join("\n");
  const easeLines = Object.keys(motion.easing)
    .map((k) => `  --ease-${k}: var(--hx-ease-${k});`)
    .join("\n");

  return `/* GENERATED by @healuxa/design-tokens (scripts/build-css.ts). Do not edit.
   Usage (Tailwind v4):  @import "tailwindcss"; @import "@healuxa/design-tokens/tokens.css"; @import "@healuxa/design-tokens/theme.css"; */
@theme inline {
  --color-*: initial;
  --color-white: #ffffff;
  --color-black: #000000;
${colorLines}
${fontLines}
${textLines}
${radiusLines}
${shadowLines}
${easeLines}
  --spacing: 0.25rem;
  --breakpoint-sm: 40rem;
  --breakpoint-md: 48rem;
  --breakpoint-lg: 64rem;
  --breakpoint-xl: 80rem;
}
`;
}
